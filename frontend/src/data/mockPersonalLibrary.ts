export function getPersonalLibrary(id: string): PersonalLibrary {
  return (
    personalLibraryCatalog[id] ?? {
      id,
      name: 'Reading List',
      description: 'A personal collection of manhwa.',
      entryCount: 0,
      coverFrom: '#4a2c5c',
      coverTo: '#8b3a4a',
      coverAccent: '#d4af37',
    }
  )
}

export function getPersonalLibraryEntries(id: string): LibraryEntry[] {
  return personalLibraryEntries[id] ?? []
}

export function getTabCounts(entries: LibraryEntry[]) {
  return {
    all: entries.length,
    reading: entries.filter((e) => e.status === 'reading').length,
    completed: entries.filter((e) => e.status === 'completed').length,
    'on-hold': entries.filter((e) => e.status === 'on-hold').length,
    dropped: entries.filter((e) => e.status === 'dropped').length,
    wishlist: entries.filter((e) => e.status === 'wishlist').length,
  }
}
